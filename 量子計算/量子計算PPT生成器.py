def save_presentation_outline():
    """保存PPT大綱到文件"""
    
    presentation = create_presentation_outline()
    
    # 生成Markdown格式的PPT內容
    content = f"""# {presentation['title']}

## 基本信息
- **副標題**: {presentation['subtitle']}
- **演講時長**: {presentation['duration']}
- **受眾**: RF專業團隊

---

"""
    
    for section in presentation['sections']:
        content += f"## {section['title']}\n\n"
        
        for slide in section['slides']:
            content += f"### {slide['title']}\n\n"
            for line in slide['content']:
                content += f"{line}\n"
            content += "\n---\n\n"
    
    # 保存到文件
    filename = "量子計算PPT_內容大綱.md"
    with open(filename, 'w', encoding='utf-8') as f:
        f.write(content)
    
    print(f"✅ PPT內容大綱已生成：{filename}")
    
    # 同時生成簡化版PPT腳本
    create_simple_ppt_script(presentation)

